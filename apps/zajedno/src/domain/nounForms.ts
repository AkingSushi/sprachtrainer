const key = (de: string, sr: string) => JSON.stringify([de, sr]);
const nouns = new Map(nounRows.map(([de, sr, dePlural, srPlural]) => [key(de, sr), { de: dePlural, sr: srPlural }]));

export function nounForms(entry: Entry & { dePlural?: string; srPlural?: string }): NounForms {
  if (entry.kind !== 'word') return {};
  const known = nouns.get(key(entry.de, entry.sr));
  const result: NounForms = {};
  for (const language of ['de', 'sr'] as const) {
    const custom = language === 'de' ? entry.dePlural : entry.srPlural;
    if (custom) { result[language] = { form: custom, usage: 'plural' }; continue; }
    const value = known?.[language];
    if (value) result[language] = value === '*' ? { form: '', usage: 'mass' }
      : value === '=' ? { form: entry[language], usage: 'alreadyPlural' }
      : value.startsWith('~') ? { form: value.slice(1), usage: 'collective' } : { form: value, usage: 'plural' };
  }
  return result;
}